"""Per-group ModelConfigs (spec §4; plan Task 11): a group with `gateway: true` gets, for each model
it uses, a generated copy of the reference ModelConfig that differs only in its name, its baseUrl
(the gateway) and its apiKeySecret (the group's virtual key). Its agents use those; every other
agent keeps the reference config until its group moves."""
import yaml

import model_budgets as mb
from conftest import REPO

CONFIGS = REPO / "base-apps/kagent/model-configs"
TEMPLATES = REPO / "base-apps/kagent/agent-templates"
GENERATED = "GENERATED by scripts/gen-model-budgets.py"


def _load(path):
    return next(d for d in yaml.safe_load_all(path.read_text()) if d)


def reference(model):
    return _load(CONFIGS / f"anthropic-{model}.yaml")


def template_model(agent):
    doc = _load(TEMPLATES / f"{agent}.yaml")
    return doc["spec"]["modelConfig"]["name"]


def test_each_moved_group_has_one_config_per_model_that_differs_only_where_it_must():
    for group, g in mb.load()["groups"].items():
        for model in g["models"]:
            path = CONFIGS / f"anthropic-{model}-{group}.yaml"
            if not g["gateway"]:
                assert not path.exists(), f"{group} has not moved: no generated config"
                continue
            assert GENERATED in path.read_text()
            got, ref = _load(path), reference(model)
            assert got["metadata"]["name"] == f"anthropic-{model}-{group}"
            assert got["spec"]["anthropic"].pop("baseUrl") == mb.GATEWAY_URL
            assert got["spec"].pop("apiKeySecret") == f"model-gateway-key-{group}"
            ref["spec"].pop("apiKeySecret")
            assert got["spec"] == ref["spec"]
            assert got["metadata"]["labels"] == {**ref["metadata"]["labels"], "model-gateway/group": group}


def test_agents_use_their_groups_config_once_the_group_moved():
    for group, g in mb.load()["groups"].items():
        for agent in g["agents"]:
            used = template_model(agent)
            ref = next(m for m in g["models"] if used in (f"anthropic-{m}", f"anthropic-{m}-{group}"))
            want = f"anthropic-{ref}-{group}" if g["gateway"] else f"anthropic-{ref}"
            assert used == want, f"{agent} ({group}, gateway {g['gateway']}): {used} != {want}"


def test_no_stale_generated_config():
    table = mb.load()["groups"]
    wanted = {f"anthropic-{m}-{grp}.yaml" for grp, g in table.items() if g["gateway"] for m in g["models"]}
    generated = {p.name for p in CONFIGS.glob("*.yaml") if GENERATED in p.read_text()}
    assert generated == wanted


def test_k8s_reader_is_the_first_group_on_the_gateway():
    table = mb.load()["groups"]
    assert table["k8s-reader"]["gateway"] is True
    assert template_model("k8s-reader") == "anthropic-claude-haiku-5-5-k8s-reader"
