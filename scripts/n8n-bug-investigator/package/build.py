#!/usr/bin/env python3
"""Build the bug investigator's two n8n workflows from config.toml.

    python3 build.py config.toml               # writes out/bug-investigator-run.json and out/bug-investigator.json
    python3 build.py config.toml --out build/

Python 3.11 or newer, standard library only. Import the child workflow first (README.md).
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
import tomllib
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
# In the zip the engine sits beside this file; in the source repository it is the parent folder.
ENGINE = HERE / "engine" if (HERE / "engine").is_dir() else HERE.parent
BANNER = "// Generated by build.py (n8n bug investigator) from engine/lib and engine/nodes."
FIXED_NODES = {"Called by the picker", "Gather facts", "Gathered?", "Investigate", "Verify", "Render and post",
               "Agent failed", "Finish", "Pick issue", "Investigate issue"}
MODEL_NODE = "Anthropic model"
DEADLINE_MS = 240_000        # n8n's task runner stops a Code node at 300 s
CHILD_TIMEOUT, PARENT_TIMEOUT = 900, 960

TELEMETRY_LOKI = """\
- Telemetry: `query_loki_logs`, `query_loki_stats`, `list_loki_label_names`, `list_loki_label_values`
  (datasourceUid `{loki}`) and `query_prometheus` (datasourceUid `{prometheus}`).{scope} Put a
  `|= "..."` substring filter before any regex or `| json`, pass explicit RFC 3339 start and end
  times, and keep windows to what you need."""
TELEMETRY_LOKI_EVIDENCE = """\
- `logql` / `promql`: the exact query is re-run over [`start`, `end`] (at most 24 h).
  `expect: "found"` needs at least one log line or one non-zero sample; `expect: "none"` needs
  none. The query field is the complete string you passed to the tool, copied character for
  character, with no comments or shorthand (a description goes in `detail`)."""
TELEMETRY_UNCHECKED = """\
- Telemetry: the tools described under "Telemetry pointers" in the facts. The script cannot
  re-check telemetry: never cite it as an evidence item. Say what you saw in a hypothesis's
  `test`, and list the telemetry you relied on in `could_not_check`."""
TELEMETRY_NONE = "- No telemetry: you have no log or metric tools."


class ConfigError(Exception):
    pass


def _load_builder():
    spec = importlib.util.spec_from_file_location("n8n_bug_investigator_builder", ENGINE / "builder.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _need(table: dict, key: str, where: str):
    v = table.get(key)
    if v in (None, ""):
        raise ConfigError(f"[{where}] {key} is required")
    return v


def _credential(t: dict) -> dict | None:
    return {"id": t["credential_id"], "name": t.get("credential_name") or t["credential_id"]} if t.get("credential_id") else None


def _prompt(cfg: dict, base: Path, telemetry: str, evidence: str) -> str:
    app, gh = cfg.get("app", {}), cfg["github"]
    path = base / app.get("prompt_file", "prompt.md")
    if not path.is_file():
        raise ConfigError(f"[app] prompt_file: {path} does not exist")
    owner, _, name = gh["repo"].partition("/")
    values = {"app": _need(app, "name", "app"), "repo": gh["repo"], "owner": owner, "repo_name": name,
              "docs_dir": gh.get("docs_dir", "docs"), "telemetry": telemetry, "telemetry_evidence": evidence}
    text = path.read_text()
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", v)
    left = sorted(set(re.findall(r"\{\{\s*([A-Za-z_]+)\s*\}\}", text)))
    if left:
        raise ConfigError(f"{path.name}: unknown placeholder(s) {', '.join(left)}")
    # A dropped placeholder line leaves an empty bullet slot; squeeze the blank lines it leaves.
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


def settings(cfg: dict, base: Path) -> dict:
    """The builder's settings from a parsed config.toml (`base`: the folder prompt_file is relative to)."""
    gh = cfg.get("github") or {}
    repo = _need(gh, "repo", "github")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
        raise ConfigError(f"[github] repo must be owner/name, not {repo!r}")
    not_before = _need(gh, "not_before", "github")
    try:
        datetime.fromisoformat(str(not_before).replace("Z", "+00:00"))
    except ValueError:
        raise ConfigError(f"[github] not_before must be an RFC 3339 time like 2026-11-01T00:00:00Z, not {not_before!r}") from None
    labels = {k: str(v) for k, v in (cfg.get("labels") or {}).items()}
    unknown = set(labels) - {"bug", "lock", "done", "failed", "skip"}
    if unknown:
        raise ConfigError(f"[labels] unknown key(s): {', '.join(sorted(unknown))}")
    model = cfg.get("model") or {}
    if model.get("prompt_caching", "5m") not in ("disabled", "5m", "1h"):
        raise ConfigError('[model] prompt_caching must be "disabled", "5m" or "1h"')
    wf = cfg.get("workflows") or {}
    mcp = cfg.get("mcp") or []
    if not mcp:
        raise ConfigError("add at least one [[mcp]] block (the GitHub MCP server)")
    nodes = [_need(t, "node", "mcp") for t in mcp]
    clash = (set(nodes) & (FIXED_NODES | {MODEL_NODE})) | {n for n in nodes if nodes.count(n) > 1}
    if clash:
        raise ConfigError(f"[[mcp]] node names must be unique and not a fixed node's name: {', '.join(sorted(clash))}")
    tel = cfg.get("telemetry") or {}
    dep = cfg.get("deploy") or {}
    if bool(dep.get("repo")) != bool(dep.get("path")):
        raise ConfigError("[deploy] set both repo and path, or neither")
    every = int((cfg.get("schedule") or {}).get("every_minutes", 5))
    if not 1 <= every <= 60:
        raise ConfigError("[schedule] every_minutes must be 1 to 60")

    datasources = {"loki": str(tel.get("loki_uid", "")), "prometheus": str(tel.get("prometheus_uid", ""))}
    if tel.get("url"):
        scope = f' Every Loki selector and Prometheus query must include `namespace="{tel["namespace"]}"`.' if tel.get("namespace") else ""
        telemetry, evidence = TELEMETRY_LOKI.format(scope=scope, **datasources), TELEMETRY_LOKI_EVIDENCE
    elif tel.get("notes"):
        telemetry, evidence = TELEMETRY_UNCHECKED, ""
    else:
        telemetry, evidence = TELEMETRY_NONE, ""

    config = {
        "repo": repo, "namespace": str(tel.get("namespace", "")), "days": 14, "deadlineMs": DEADLINE_MS,
        "telemetryUrl": tel.get("url") or None, "grafanaUrl": tel.get("grafana_url") or None,
        "datasources": datasources, "telemetryNotes": [str(x) for x in tel.get("notes", [])],
        "deployRepo": dep.get("repo") or None, "deployPath": dep.get("path") or None,
        "docsDir": str(gh.get("docs_dir", "docs")).strip("/") or "docs",
        "model": _need(model, "name", "model"), "notBefore": not_before,
        "tokenName": str(gh.get("token_name", "BUG_INVESTIGATOR_GH_TOKEN")),
        "labels": labels, "trustedBots": [str(x) for x in gh.get("trusted_bots", [])],
        "comment": {k: str(v) for k, v in (cfg.get("comment") or {}).items() if k in ("mode", "header", "footer")},
        "watchBranches": None,
        "tools": [str(x) for t in mcp for x in t.get("tools", [])],
    }
    return {
        "ids": {"parent": wf.get("parent_id", "bug-investigator"), "child": wf.get("child_id", "bug-investigator-run")},
        "names": {"parent": wf.get("parent_name", "Bug investigator: pick"), "child": wf.get("child_name", "Bug investigator: investigate")},
        "everyMinutes": every,
        "timeouts": {"parent": PARENT_TIMEOUT, "child": CHILD_TIMEOUT},
        "model": {"name": model["name"], "nodeName": MODEL_NODE, "maxTokens": int(model.get("max_tokens", 16000)),
                  "maxIterations": int(model.get("max_iterations", 40)), "promptCaching": model.get("prompt_caching", "5m"),
                  "credential": _credential(model)},
        "systemPrompt": _prompt(cfg, base, telemetry, evidence),
        "mcp": [{"node": t["node"], "url": _need(t, "url", "mcp"), "tools": list(t.get("tools", [])),
                 "auth": t.get("auth", "none"), "credential": _credential(t)} for t in mcp],
        "config": config,
        "banner": BANNER,
    }


def build(config_path: Path) -> dict[str, dict]:
    with open(config_path, "rb") as f:
        cfg = tomllib.load(f)
    s = settings(cfg, config_path.resolve().parent)
    builder = _load_builder()
    try:
        return builder.build_workflows(s, ENGINE / "lib", ENGINE / "nodes")
    except ValueError as e:
        raise ConfigError(str(e)) from None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", type=Path, help="your config.toml")
    ap.add_argument("--out", type=Path, default=Path("out"), help="folder for the workflow files (default: out)")
    args = ap.parse_args(argv)
    try:
        workflows = build(args.config)
    except (ConfigError, tomllib.TOMLDecodeError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    args.out.mkdir(parents=True, exist_ok=True)
    for name in ("bug-investigator-run.json", "bug-investigator.json"):
        (args.out / name).write_text(json.dumps(workflows[name], indent=2, ensure_ascii=False) + "\n")
        print(f"wrote {args.out / name}")
    print("next: import bug-investigator-run.json first, then bug-investigator.json (README.md, step 4)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
