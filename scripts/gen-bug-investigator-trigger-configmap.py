#!/usr/bin/env python3
"""Generate base-apps/kagent/bug-investigator-trigger-code-configmap.yaml from the trigger script and
the A2A client it imports, and pin the CronJob's checksum/code annotation. CI runs --check.

    scripts/gen-bug-investigator-trigger-configmap.py --repo-root .
    scripts/gen-bug-investigator-trigger-configmap.py --repo-root . --check

Same pattern as gen-docs-checker-trigger-configmap.py: the CronJob runs the one tested file with
python:3.12 (the full image, which has git) and no pip install (both files are standard-library
only); an image build per edit is a drift trap, a hand-copied ConfigMap a worse one. The
bug-investigator package it imports comes from its own generated ConfigMap, bug-investigator-core.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

import yaml

SOURCES = {"bug_investigator_trigger.py": "scripts/bug_investigator_trigger.py",
           "kagent_a2a.py": "scripts/kagent_a2a.py"}
OUT = "base-apps/kagent/bug-investigator-trigger-code-configmap.yaml"
CRONJOB = "base-apps/kagent/bug-investigator-trigger.yaml"

HEADER = """\
# base-apps/kagent/bug-investigator-trigger-code-configmap.yaml
# GENERATED by scripts/gen-bug-investigator-trigger-configmap.py from scripts/bug_investigator_trigger.py
# and scripts/kagent_a2a.py. Do not edit; change the sources and re-run the generator. CI checks
# drift. Mounted at /opt/bug-investigator-trigger by the CronJob in bug-investigator-trigger.yaml.
"""


class _Literal(str):
    pass


def _literal(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.add_representer(_Literal, _literal)


def render(repo: Path) -> str:
    data = {key: _Literal((repo / src).read_text()) for key, src in SOURCES.items()}
    cm = {"apiVersion": "v1", "kind": "ConfigMap",
          "metadata": {"name": "bug-investigator-trigger-code", "namespace": "kagent",
                       "labels": {"app": "bug-investigator-trigger"}},
          "data": data}
    return HEADER + "---\n" + yaml.dump(cm, sort_keys=False, width=10_000, allow_unicode=True)


def checksum(text: str) -> str:
    """sha256 (first 16 hex) over the ConfigMap's values sorted by key: the eval gate's formula."""
    cm = yaml.safe_load(text)
    return hashlib.sha256("".join(cm["data"][k] for k in sorted(cm["data"])).encode()).hexdigest()[:16]


def render_cronjob(repo: Path, code_text: str) -> str:
    text = (repo / CRONJOB).read_text()
    new, n = re.subn(r"(checksum/code: )\S+", rf"\g<1>{checksum(code_text)}", text)
    if n != 1:
        raise SystemExit(f"{CRONJOB}: expected exactly one checksum/code annotation, found {n}")
    return new


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed manifests are stale")
    args = ap.parse_args(argv)
    repo = args.repo_root
    code = render(repo)
    cron = render_cronjob(repo, code)
    drift = [p for p, want in ((OUT, code), (CRONJOB, cron))
             if not (repo / p).exists() or (repo / p).read_text() != want]
    if args.check:
        for p in drift:
            print(f"{p} is out of date: run scripts/gen-bug-investigator-trigger-configmap.py --repo-root .",
                  file=sys.stderr)
        return 1 if drift else 0
    (repo / OUT).write_text(code)
    (repo / CRONJOB).write_text(cron)
    print(f"wrote {OUT} and pinned checksum/code in {CRONJOB}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
