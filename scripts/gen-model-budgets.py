# ------------------------------------------------------------------ the gateway's config

PROVIDER_KEY_FILE = "/var/run/model-gateway/anthropic/api-key"
# No password in the URL: in Kubernetes agentgateway logs its whole startup config, database URL
# included, unredacted (agentgateway-app run.rs). sqlx takes the password from PGPASSWORD, which
# the Deployment sets from Secret model-gateway-env (local proof check 12: no secret in the logs).
DB_URL = ("postgres://model_gateway@postgresql.postgresql.svc.cluster.local:5432/model_gateway"
          "?sslmode=disable")
LLM_PORT = 8080           # the front listener: what Substrate's egress connects to
BUDGET_PORT = 8081        # the llm listener (keys, budgets, provider key), on 127.0.0.1 only
METRICS_PORT = 15020      # agentgateway's default stats address (the MCP adapters use it too)
READY_PORT = 15021        # agentgateway's default readiness address
ADMIN_PORT = 15000        # agentgateway's default admin/UI address (127.0.0.1): /api/budgets
# The gateway's own 429 for an exhausted budget carries Retry-After = the seconds left in the
# window; the Anthropic Go SDK (v1.80.0) waits that long with no limit, twice. x-should-retry:
# false makes it fail at once (spec §3.2). A response policy does not reach a response the
# gateway generates itself (local proof, 2026-10-23), so the llm listener sits behind a front
# listener in the same process: there the refusal is an upstream response and its rules apply.
# The front tells the refusal from Anthropic's own 429 by Anthropic's `request-id` header, which
# every Anthropic response carries and the gateway's refusal does not; any x-should-retry
# Anthropic sent is passed through, so its own 429s and 529s keep their normal retries.
NO_RETRY = ('response.code == 429 && !("request-id" in response.headers) ? "false" : '
            '("x-should-retry" in response.headers ? response.headers["x-should-retry"] : "")')


def _catalog(models: set[str]) -> dict:
    """The collector's prices (§V.105) as agentgateway's inline model catalog."""
    prices = mb.collector_prices()
    out = {}
    for model in sorted(models):
        tiers = prices[model]

        def rates(t):
            return {"input": str(t["input"]), "output": str(t["output"]),
                    "cacheRead": str(t["cache_read"]), "cacheWrite": str(t["cache_write"])}

        entry = {"rates": rates(tiers[0])}
        if len(tiers) > 1:
            entry["tiers"] = [{"contextOver": t["over"], "rates": rates(t)} for t in tiers[1:]]
        out[model] = entry
    return {"providers": {"anthropic": {"models": out}}}


def gateway_config(keys: dict[str, str], db_url: str, *, table: dict | None = None,
                   provider_key_file: str = PROVIDER_KEY_FILE, base_url: str | None = None,
                   tracing: bool = True) -> dict:
    """agentgateway v1.6.0 standalone config, `llm` mode (the documented LLM-gateway shape).

    keys: group → the value the config holds for that group's virtual key (in the cluster an
    env reference, `$MODEL_GATEWAY_KEY_<GROUP>`; in the local proof a literal test key).
    base_url: the upstream; None means the provider's default (https://api.anthropic.com)."""
    table = table or mb.load()
    groups = table["groups"]
    models = sorted({m for g in groups.values() for m in g["models"]})
    params: dict = {"apiKey": {"file": provider_key_file}}
    if base_url:
        params["baseUrl"] = base_url
    cfg: dict = {
        "config": {
            "statsAddr": f"0.0.0.0:{METRICS_PORT}",
            "readinessAddr": f"0.0.0.0:{READY_PORT}",
            "database": {"url": db_url},
            "modelCatalog": [{"inline": _catalog(set(models))}],
            "metrics": {"fields": {"add": {"group": 'default(apiKey.group, "")'}}},
        },
        "binds": [{"port": LLM_PORT, "listeners": [{"name": "front", "protocol": "HTTP", "routes": [{
            "name": "budget-listener",
            "policies": {"transformations": {"response": {"set": {"x-should-retry": NO_RETRY}}}},
            "backends": [{"host": f"127.0.0.1:{BUDGET_PORT}", "weight": 100}]}]}]}],
        "gateways": {"llm": {"port": BUDGET_PORT, "bindAddress": "127.0.0.1"}},
        "llm": {
            "gateways": "llm",
            "models": [{"name": m, "provider": "anthropic", "passthrough": "detect",
                        "params": dict(params)} for m in models],
            "policies": {
                "apiKey": {
                    "mode": "strict",
                    "location": {"header": {"name": "x-api-key"}},
                    # metadata.name is required on a key with a budget (1.6.0 refuses to start
                    # without it). The budget's counter is keyed by the key's hash, so a rotated
                    # key starts its group's day again at zero (local proof, 2026-10-23).
                    "keys": [{"key": keys[name], "metadata": {"name": name, "group": name},
                              "allowedModels": list(g["models"]),
                              "budgets": [{"name": "daily",
                                           "limit": {"unit": "USD", "amount": g["daily_usd"]},
                                           "window": {"rolling": table["window"]},
                                           "onBudgetExceeded": "Block"}]}
                             for name, g in groups.items()],
                },
            },
        },
    }
    if tracing:
        cfg["frontendPolicies"] = {"tracing": {
            "host": "otel-collector.tracing.svc.cluster.local:4317", "protocol": "grpc",
            "randomSampling": "true", "resources": {"service.name": '"model-gateway"'}}}
    return cfg


def _window_total():
    """window_total() from the dashboards generator: the one tested way to sum rare counters."""
    path = Path(__file__).resolve().parent / "gen-agent-dashboards.py"
    spec = importlib.util.spec_from_file_location("gen_agent_dashboards", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.window_total


# ------------------------------------------------------------------ PromQL

def budget_labels(table: dict | None = None) -> list[dict[str, str]]:
    """One label set per group: the labels each alert instance carries."""
    table = table or mb.load()
    out = []
    for name, g in table["groups"].items():
        agents = ", ".join(g["agents"]) if g["agents"] else CHART_DEFAULT_AGENTS
        out.append({"group": name, "agents": agents, "budget_usd": f"{g['daily_usd']:.2f}",
                    "enforced": "true" if g["gateway"] else "false"})
    return out


def _budget_vector(table: dict) -> str:
    """Each group's daily budget as a constant series carrying its labels."""
    keys = ("group", "agents", "budget_usd", "enforced")
    terms = []
    for labels, g in zip(budget_labels(table), table["groups"].values()):
        terms.append("label_replace(" * len(keys) + f"vector({g['daily_usd']}),\n"
                     + ",\n".join(f'  "{k}", "{labels[k]}", "", "")' for k in keys))
    return "\nor\n".join(terms)


def _spend_by_group(table: dict) -> str:
    """Each group's estimated spend over the last 24 hours (agents in no group are dropped later)."""
    named = [(name, "|".join(g["agents"])) for name, g in table["groups"].items() if g["agents"]]
    expr = ("label_replace(" * len(named) + "\n"
            # one line per part, to stay under yamllint's 200 characters
            + _window_total()(COST, "service_name", table["window"]).replace(" or ", "\n  or ") + ",\n"
            + ",\n".join(f'  "group", "{name}", "service_name", "{rx}")' for name, rx in named))
    return f"sum by (group) (\n{expr}\n)"


def ratio_expr(table: dict | None = None) -> str:
    """Spend / budget per group: the alert's condition."""
    table = table or mb.load()
    return (f"({_spend_by_group(table)})\n/ on(group) group_left(agents, budget_usd, enforced) (\n"
            f"{_budget_vector(table)}\n)")


def spend_expr(table: dict | None = None) -> str:
    """Spend per group, with the same labels as ratio_expr so $values.spend matches."""
    table = table or mb.load()
    return (f"({_spend_by_group(table)})\n+ on(group) group_left(agents, budget_usd, enforced) (0 * (\n"
            f"{_budget_vector(table)}\n))")


# ------------------------------------------------------------------ Grafana rules

RUNBOOK = (
    "Who spent it: Grafana, Agents → Agent Platform (tokens and estimated cost per agent). A loop "
    "or a busy day? A budget changes only by a pull request: base-apps/model-gateway/budgets.yaml, "
    "then scripts/gen-model-budgets.py --write. This is the estimate over a rolling 24 hours; the "
    "gateway's own day starts at 00:00 UTC (base-apps/model-gateway/runbook.md).")

_WHO = "Agent group {{ $labels.group }} ({{ $labels.agents }})"
_SPENT = "${{ with $values.spend }}{{ printf \"%.2f\" .Value }}{{ end }}"
NEAR_SUMMARY = (
    f"{_WHO} spent {_SPENT} in the last 24 hours: "
    "{{ with $values.ratio }}{{ humanizePercentage .Value }}{{ end }} of its "
    "${{ $labels.budget_usd }} daily budget. {{ if eq $labels.enforced \"true\" }}The gateway "
    "refuses its model calls once the day's spend reaches the budget.{{ else }}Not enforced yet: "
    "the group's model calls do not go through the gateway.{{ end }}")
OVER_SUMMARY = (
    f"{_WHO} spent {_SPENT} in the last 24 hours, over its ${{{{ $labels.budget_usd }}}} daily "
    "budget. {{ if eq $labels.enforced \"true\" }}The gateway refuses its model calls until the "
    "day's spend is back under the budget (00:00 UTC).{{ else }}Nothing is blocked yet: the group "
    "does not use the gateway.{{ end }}")


def _prom(ref: str, expr: str) -> dict:
    return {"refId": ref, "relativeTimeRange": {"from": 600, "to": 0}, "datasourceUid": PROM_UID,
            "model": {"refId": ref, "datasource": {"type": "prometheus", "uid": PROM_UID},
                      "instant": True, "range": False, "expr": expr}}


def _threshold(value: float) -> dict:
    return {"refId": "threshold", "relativeTimeRange": {"from": 600, "to": 0}, "datasourceUid": "__expr__",
            "model": {"refId": "threshold", "type": "threshold", "expression": "ratio",
                      "conditions": [{"evaluator": {"type": "gt", "params": [value]}}]}}


def _rule(uid: str, title: str, severity: str, threshold: float, summary: str, table: dict) -> dict:
    return {"uid": uid, "title": title, "condition": "threshold", "for": "0m",
            "annotations": {"summary": summary, "runbook": RUNBOOK},
            "labels": {"severity": severity, "pillar": "cost"},
            "noDataState": "OK", "execErrState": "KeepLast",
            "data": [_prom("ratio", ratio_expr(table)), _prom("spend", spend_expr(table)),
                     _threshold(threshold)]}


def rule_group(table: dict | None = None) -> dict:
    table = table or mb.load()
    return {"orgId": 1, "name": "agent-budgets", "folder": "Agent Budgets", "interval": "5m",
            "rules": [
                _rule("agent-budget-near", "Agent near its daily budget", "warning", table["warn_at"],
                      NEAR_SUMMARY, table),
                _rule("agent-budget-over", "Agent over its daily budget", "critical", 0.999,
                      OVER_SUMMARY, table),
            ]}


class _Dumper(yaml.SafeDumper):
    """Indented lists, like the hand-written rules around the block."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _str(dumper, value):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def _block(table: dict) -> str:
    body = yaml.dump([rule_group(table)], Dumper=_Dumper, sort_keys=False, width=150,
                     default_flow_style=False, allow_unicode=True)
    lines = [BEGIN,
             "      # The daily budget alerts (spec §5). Each group's estimated spend over the last",
             "      # 24 hours (window_total, never increase(): §V.106) over its daily budget; the",
             "      # dispatcher routes both to `none` (an investigation would spend the budget).",
             *[("      " + line) if line else "" for line in body.rstrip("\n").split("\n")],
             END]
    return "\n".join(lines) + "\n"


def alerting_text(current: str, table: dict) -> str:
    block = _block(table)
    if BEGIN in current:
        start = current.index(BEGIN)
        end = current.index(END, start) + len(END) + 1
        return current[:start] + block + current[end:]
    return current.rstrip("\n") + "\n" + block


def alerting_checksum(text: str) -> str:
    cm = [d for d in yaml.safe_load_all(text) if d and d.get("kind") == "ConfigMap"][0]
    return hashlib.sha256(json.dumps(cm["data"], sort_keys=True).encode()).hexdigest()


def deploy_text(current: str, checksum: str) -> str:
    new, n = re.subn(r"(checksum/alerting: )[0-9a-f]{64}", rf"\g<1>{checksum}", current)
    if n != 1:
        raise SystemExit(f"{GRAFANA_DEPLOY}: expected one checksum/alerting annotation, found {n}")
    return new


GATEWAY_CM_HEADER = """\
# The model gateway's config (agentgateway v1.6.0, standalone). GENERATED by
# scripts/gen-model-budgets.py from base-apps/model-gateway/budgets.yaml and the collector's prices:
# edit those, then run `scripts/gen-model-budgets.py --write`. Spec §3.1a, §3.2.
#
# Two listeners in one process. The front (8080), which Substrate's egress connects to, proxies to
# the llm listener (127.0.0.1:8081), which checks the group's virtual key and its daily budget and
# swaps in the real key. The front exists for one rule: it marks the gateway's own budget refusal
# x-should-retry: false, so a blocked agent fails at once instead of sleeping until midnight.
# $MODEL_GATEWAY_KEY_* are expanded from the environment (Secret model-gateway-env) when the
# gateway reads this file, and the database password comes from PGPASSWORD: no secret is in git or
# in the gateway's startup log.
"""


def gateway_configmap(table: dict) -> str:
    keys = {g: "$" + mb.env_name(g) for g in table["groups"]}
    body = yaml.dump(gateway_config(keys, DB_URL, table=table), Dumper=_Dumper, sort_keys=False,
                     width=150, default_flow_style=False, allow_unicode=True)
    cm = {"apiVersion": "v1", "kind": "ConfigMap",
          "metadata": {"name": "model-gateway-config", "namespace": "model-gateway",
                       "labels": {"app.kubernetes.io/name": "model-gateway",
                                  "app.kubernetes.io/part-of": "model-gateway"}},
          "data": {"config.yaml": body}}
    return GATEWAY_CM_HEADER + yaml.dump(cm, Dumper=_Dumper, sort_keys=False, width=150,
                                         default_flow_style=False, allow_unicode=True)


def outputs(repo: Path = REPO) -> dict[str, str]:
    table = mb.load(repo / "base-apps/model-gateway/budgets.yaml")
    alerting = alerting_text((repo / ALERTING).read_text(), table)
    return {ALERTING: alerting,
            GRAFANA_DEPLOY: deploy_text((repo / GRAFANA_DEPLOY).read_text(), alerting_checksum(alerting)),
            GATEWAY_CM: gateway_configmap(table)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for rel, text in outputs().items():
        path = REPO / rel
        if not path.exists() or path.read_text() != text:
            stale.append(rel)
            if args.write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if args.check and stale:
        print("stale, run scripts/gen-model-budgets.py --write: " + ", ".join(stale), file=sys.stderr)
        return 1
    for rel in stale if args.write else []:
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
