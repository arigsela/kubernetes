"""Generate everything base-apps/model-gateway/budgets.yaml decides.

    ./scripts/gen-model-budgets.py --write    # regenerate
    ./scripts/gen-model-budgets.py --check    # CI: fail if a generated file is stale

Outputs:
  * the `agent-budgets` rule group in base-apps/logging/grafana-alerting.yaml (between the BEGIN
    and END markers), and the `checksum/alerting` annotation that restarts Grafana on a change;
  * base-apps/model-gateway/configmap.yaml, the gateway's config (gateway_config()).

Spec: docs/superpowers/specs/2026-10-23-model-gateway-budgets-design.md (§2, §5); SPEC §V.108.
"""
