#!/usr/bin/env python3
"""Generate base-apps/kagent/eval-gate-code-configmap.yaml from the eval scripts and the
corpus, and pin the Job's checksum/code annotation. CI runs --check.

    scripts/gen-eval-gate-configmap.py --repo-root .
    scripts/gen-eval-gate-configmap.py --repo-root . --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

SOURCES = {"eval_gate.py": "scripts/eval_gate.py",
           "kagent_a2a.py": "scripts/kagent_a2a.py",
           "score_eval.py": "scripts/score-eval.py",
           "capture_eval_answers.py": "scripts/capture-eval-answers.py"}
CORPUS_DIR = "tests/eval-corpus"
OUT = "base-apps/kagent/eval-gate-code-configmap.yaml"
JOB = "base-apps/kagent/eval-gate-job.yaml"

HEADER = """\
# base-apps/kagent/eval-gate-code-configmap.yaml
# GENERATED by scripts/gen-eval-gate-configmap.py from scripts/eval_gate.py, kagent_a2a.py,
# score-eval.py, capture-eval-answers.py and tests/eval-corpus/*.yaml (as JSON: the job has no
# YAML parser). Do not edit; change the sources and re-run the generator. CI checks drift.
# Mounted at /opt/eval-gate by eval-gate-job.yaml (code and corpus__<agent>.json side by side).
"""


class _Literal(str):
    pass


def _literal(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.add_representer(_Literal, _literal)


def render(repo: Path) -> str:
    data = {key: _Literal((repo / src).read_text()) for key, src in SOURCES.items()}
    for p in sorted((repo / CORPUS_DIR).glob("*.yaml")):
        doc = yaml.safe_load(p.read_text()) or {}
        if doc.get("entries"):
            data[f"corpus__{p.stem}.json"] = _Literal(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    cm = {"apiVersion": "v1", "kind": "ConfigMap",
          "metadata": {"name": "eval-gate-code", "namespace": "kagent", "labels": {"app": "eval-gate"}},
          "data": data}
    return HEADER + "---\n" + yaml.dump(cm, sort_keys=False, width=10_000, allow_unicode=True)


def checksum(text: str) -> str:
    cm = yaml.safe_load(text)
    return hashlib.sha256("".join(cm["data"][k] for k in sorted(cm["data"])).encode()).hexdigest()[:16]


def render_job(repo: Path, code_text: str) -> str:
    job = (repo / JOB).read_text()
    new, n = re.subn(r"(checksum/code: )\S+", rf"\g<1>{checksum(code_text)}", job)
    if n != 1:
        raise SystemExit(f"{JOB}: expected exactly one checksum/code annotation, found {n}")
    return new


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    repo = args.repo_root
    code = render(repo)
    job = render_job(repo, code)
    drift = [p for p, want in ((OUT, code), (JOB, job))
             if not (repo / p).exists() or (repo / p).read_text() != want]
    if args.check:
        for p in drift:
            print(f"{p} is out of date: run scripts/gen-eval-gate-configmap.py --repo-root .", file=sys.stderr)
        return 1 if drift else 0
    (repo / OUT).write_text(code)
    (repo / JOB).write_text(job)
    print(f"wrote {OUT} and pinned checksum/code in {JOB}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
